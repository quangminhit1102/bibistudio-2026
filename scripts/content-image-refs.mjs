import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { root, isMain } from "./runtime.mjs";

// The first content seed stored placeholder image references (`catalogue-image-<slug>-N`,
// `journal-cover-<slug>`) that no media endpoint serves. This tool compares the seed with a
// site's public API and writes the SQL that points those rows at the public files instead.
// It only reads; a person runs the SQL.

const BACKUP = "content_image_refs_backup";
const MEDIA = "/api/media/";

/** The value the database holds for an image URL of the public API. */
const stored = (url) => (url.startsWith(MEDIA) ? url.slice(MEDIA.length) : url);

export function planImageRefs(seed, api) {
  const plan = { products: [], posts: [], skipped: [], problems: [] };
  for (const item of seed.products ?? []) {
    const found = api.products.find((p) => p.slug === item.slug);
    const note = (list, reason) => list.push({ kind: "product", slug: item.slug, reason });
    if (!found) {
      note(plan.problems, "missing from the API");
      continue;
    }
    const from = found.images.map(stored);
    const to = item.imageIds ?? [];
    if (from.join("\n") === to.join("\n")) continue;
    const seeded = from.every((id, k) => id === `catalogue-image-${item.slug}-${k}`);
    if (!seeded) note(plan.skipped, "changed in the admin");
    else if (from.length !== to.length)
      note(
        plan.problems,
        `${from.length} seeded image${from.length === 1 ? "" : "s"} in the database, ${to.length} in the seed`,
      );
    else plan.products.push({ slug: item.slug, from, to });
  }
  for (const item of seed.posts ?? []) {
    const found = api.posts.find((p) => p.slug === item.slug);
    if (!found) {
      plan.problems.push({ kind: "post", slug: item.slug, reason: "missing from the API" });
      continue;
    }
    const from = found.cover_url == null ? null : stored(found.cover_url);
    const to = item.imageId;
    if (!to?.startsWith("/") || from === to) continue;
    const note = (list, reason) => list.push({ kind: "post", slug: item.slug, reason });
    // What a seed has stored for this post so far: the placeholder, or the build's own path.
    const seeded = [`journal-cover-${item.slug}`, `/assets/blog/${to.split("/").pop()}`];
    if (!seeded.includes(from)) note(plan.skipped, "changed in the admin");
    else if (to.length > 64)
      note(plan.problems, "the path is longer than the 64 characters of image_id");
    else plan.posts.push({ slug: item.slug, from, to });
  }
  return plan;
}

const q = (value) => `'${String(value).replaceAll("\\", "\\\\").replaceAll("'", "''")}'`;
const list = (items) => items.map((item) => q(item.slug)).join(", ") || "''";

/** True only while the row's JSON array still holds exactly `values`. */
const holds = (values) =>
  [
    `JSON_LENGTH(image_ids) = ${values.length}`,
    ...values.map((v, k) => `JSON_UNQUOTE(JSON_EXTRACT(image_ids, '$[${k}]')) = ${q(v)}`),
  ].join(" AND ");

const setImages = (slug, to, from) =>
  `UPDATE products SET image_ids = ${q(JSON.stringify(to))} WHERE slug = ${q(slug)} AND ${holds(from)};`;

const header = (plan, title) =>
  `-- ${title}\n-- ${plan.products.length} products, ${plan.posts.length} posts. Generated by scripts/content-image-refs.mjs.\n`;

export function previewSql(plan) {
  return [
    header(plan, "Read only: the rows the change would touch, with their current values."),
    `SELECT 'product' AS kind, slug, image_ids AS current_value FROM products WHERE slug IN (${list(plan.products)})`,
    `UNION ALL SELECT 'post', slug, COALESCE(cover_image_id, image_id) FROM posts WHERE slug IN (${list(plan.posts)});`,
    "",
  ].join("\n");
}

export function applySql(plan) {
  return [
    header(plan, "Points seeded image references at the public files. Undo with 3-rollback.sql."),
    `CREATE TABLE IF NOT EXISTS ${BACKUP} (`,
    "  kind VARCHAR(8) NOT NULL, slug VARCHAR(191) NOT NULL, old_value TEXT NULL, old_cover TEXT NULL, saved_at DATETIME NOT NULL,",
    "  PRIMARY KEY (kind, slug)",
    ");",
    "START TRANSACTION;",
    "-- The first run keeps the values as they were; a second run does not overwrite them.",
    `INSERT INTO ${BACKUP} (kind, slug, old_value, saved_at) SELECT 'product', slug, image_ids, NOW() FROM products WHERE slug IN (${list(plan.products)}) ON DUPLICATE KEY UPDATE kind = VALUES(kind);`,
    `INSERT INTO ${BACKUP} (kind, slug, old_value, old_cover, saved_at) SELECT 'post', slug, image_id, cover_image_id, NOW() FROM posts WHERE slug IN (${list(plan.posts)}) ON DUPLICATE KEY UPDATE kind = VALUES(kind);`,
    ...plan.products.map((p) => setImages(p.slug, p.to, p.from)),
    // The cover goes to image_id, the column the admin's cover picker edits; cover_image_id
    // is emptied because the public API prefers it over image_id.
    ...plan.posts.map(
      (p) =>
        `UPDATE posts SET image_id = ${q(p.to)}, cover_image_id = NULL WHERE slug = ${q(p.slug)} AND COALESCE(cover_image_id, image_id) = ${q(p.from)};`,
    ),
    "COMMIT;",
    "",
  ].join("\n");
}

export function rollbackSql(plan) {
  return [
    header(plan, "Undoes 2-apply.sql. A row edited in the admin since then is left as it is."),
    "START TRANSACTION;",
    ...plan.products.map((p) => setImages(p.slug, p.from, p.to)),
    ...plan.posts.map(
      (p) =>
        `UPDATE posts p JOIN ${BACKUP} b ON b.kind = 'post' AND b.slug = p.slug SET p.image_id = b.old_value, p.cover_image_id = b.old_cover WHERE p.slug = ${q(p.slug)} AND p.image_id = ${q(p.to)} AND p.cover_image_id IS NULL;`,
    ),
    "COMMIT;",
    `-- When the site has been checked again: DROP TABLE ${BACKUP};`,
    "",
  ].join("\n");
}

const isImage = (response) =>
  response.status === 200 && (response.headers.get("content-type") ?? "").startsWith("image/");

async function loads(urls, base, fetchImage) {
  const result = new Map();
  const queue = [...new Set(urls)];
  await Promise.all(
    Array.from({ length: 8 }, async () => {
      for (let url; (url = queue.pop());) {
        const response = await fetchImage(new URL(url, base).href);
        result.set(url, { ok: isImage(response), status: response.status });
      }
    }),
  );
  return result;
}

/** Every seed entry must be in the API and every image the API names must load. */
export async function checkContent(seed, api, base, fetchImage) {
  const missing = [];
  for (const [kind, key] of [
    ["product", "products"],
    ["post", "posts"],
  ])
    for (const item of seed[key] ?? [])
      if (!api[key].some((found) => found.slug === item.slug))
        missing.push({ kind, slug: item.slug });
  // An entry of the seed must keep an image: the bundled one stops being shown with the fallback.
  const seeded = (key, slug, has) =>
    (seed[key] ?? []).some((item) => item.slug === slug && has(item));
  const refs = [
    ...api.products.flatMap((p) =>
      p.images.length
        ? p.images.map((url) => ({ kind: "product", slug: p.slug, url }))
        : seeded("products", p.slug, (item) => item.imageIds?.length)
          ? [{ kind: "product", slug: p.slug, url: null }]
          : [],
    ),
    ...api.posts.flatMap((p) =>
      p.cover_url || seeded("posts", p.slug, (item) => item.imageId)
        ? [{ kind: "post", slug: p.slug, url: p.cover_url ?? null }]
        : [],
    ),
  ];
  // Only the site's own files are requested; an address elsewhere is listed, not visited.
  const own = (url) => new URL(url, base).origin === new URL(base).origin;
  const external = refs.filter((ref) => ref.url && !own(ref.url));
  const state = await loads(
    refs.flatMap((ref) => (ref.url && own(ref.url) ? [ref.url] : [])),
    base,
    fetchImage,
  );
  const broken = refs.flatMap((ref) => {
    if (ref.url && !own(ref.url)) return [];
    const found = ref.url ? state.get(ref.url) : { ok: false, status: null };
    return found.ok ? [] : [{ ...ref, status: found.status }];
  });
  return { missing, broken, external, checked: state.size };
}

async function readApi(base) {
  const get = async (path) => {
    const response = await fetch(new URL(path, base));
    if (!response.ok) throw new Error(`${path} returned HTTP ${response.status}`);
    return response.json();
  };
  const [products, posts] = await Promise.all([
    get("/api/public/products"),
    get("/api/public/posts"),
  ]);
  return { products, posts };
}

// A redirect is not followed: the file itself must be at the address the database names.
const head = (url) => fetch(url, { method: "HEAD", redirect: "manual" });
const lines = (items, text) =>
  items.map((item) => `- ${item.kind} \`${item.slug}\`: ${text(item)}`);

async function main([command, ...rest]) {
  const option = (name) => (rest.includes(name) ? rest[rest.indexOf(name) + 1] : undefined);
  const base = option("--api");
  if (!["plan", "verify"].includes(command) || !base)
    throw new Error("Usage: content-image-refs.mjs plan|verify --api <site URL> [--out <dir>]");
  const seed = JSON.parse(await readFile(join(root, "backend/content-seed.json"), "utf8"));
  const api = await readApi(base);

  if (command === "verify") {
    const { missing, broken, external, checked } = await checkContent(seed, api, base, head);
    console.log(
      `${api.products.length} products, ${api.posts.length} posts, ${checked} image URLs checked at ${base}`,
    );
    for (const line of lines(missing, () => "in the seed, missing from the API")) console.log(line);
    for (const line of lines(broken, (b) => `${b.url ?? "no image"} (HTTP ${b.status ?? "-"})`))
      console.log(line);
    for (const line of lines(external, (e) => `${e.url} is on another site, not checked`))
      console.log(line);
    if (missing.length || broken.length) {
      console.log(`NOT READY: ${missing.length} missing, ${broken.length} images do not load.`);
      process.exitCode = 1;
    } else console.log("READY: every seed entry is in the API and every image loads.");
    return;
  }

  const plan = planImageRefs(seed, api);
  const targets = await loads(
    [...plan.products.flatMap((p) => p.to), ...plan.posts.map((p) => p.to)],
    base,
    head,
  );
  const live = (to) => [to].flat().every((url) => targets.get(url).ok);
  const waiting = [
    ...plan.products.filter((p) => !live(p.to)).map((p) => ({ kind: "product", ...p })),
    ...plan.posts.filter((p) => !live(p.to)).map((p) => ({ kind: "post", ...p })),
  ];
  // SQL is written only for rows whose new file is already served; the rest wait for a deploy.
  const ready = {
    ...plan,
    products: plan.products.filter((p) => live(p.to)),
    posts: plan.posts.filter((p) => live(p.to)),
  };
  const out = resolve(option("--out") ?? "content-image-refs");
  await mkdir(out, { recursive: true });
  const report = [
    `# Image references: ${base}`,
    "",
    `Read from the public API on ${new Date().toISOString()}. Nothing was changed.`,
    "",
    `- To change: ${ready.products.length} products, ${ready.posts.length} posts`,
    `- Waiting for their file to be served: ${waiting.length}`,
    `- Left alone: ${plan.skipped.length}`,
    `- Problems: ${plan.problems.length}`,
    "",
    "## Changes",
    "",
    "| Kind | Slug | Now | After |",
    "| --- | --- | --- | --- |",
    ...ready.products.map(
      (p) => `| product | ${p.slug} | ${p.from.join("<br>")} | ${p.to.join("<br>")} |`,
    ),
    ...ready.posts.map((p) => `| post | ${p.slug} | ${p.from} | ${p.to} |`),
    "",
    "## Waiting for their file to be served",
    "",
    ...lines(waiting, (w) =>
      [w.to]
        .flat()
        .filter((url) => !targets.get(url).ok)
        .join(", "),
    ),
    "",
    "## Left alone",
    "",
    ...lines(plan.skipped, (s) => s.reason),
    "",
    "## Problems",
    "",
    ...lines(plan.problems, (p) => p.reason),
    "",
  ].join("\n");
  await Promise.all([
    writeFile(join(out, "report.md"), report),
    writeFile(join(out, "1-preview.sql"), previewSql(ready)),
    writeFile(join(out, "2-apply.sql"), applySql(ready)),
    writeFile(join(out, "3-rollback.sql"), rollbackSql(ready)),
  ]);
  console.log(report.split("\n").slice(0, 8).join("\n"));
  console.log(`Written to ${out}`);
  if (waiting.length || plan.problems.length) process.exitCode = 1;
}

if (isMain(import.meta.url)) await main(process.argv.slice(2));
