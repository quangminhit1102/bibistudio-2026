CREATE TABLE access_log_current_sources (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 transport ENUM('http','https') NOT NULL UNIQUE,
 basename VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 active_snapshot_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 active_captured_at DATETIME(3) NULL,
 content_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 source_modified_at DATETIME(3) NULL,
 source_through DATETIME(3) NULL,
 last_checked_at DATETIME(3) NULL,
 last_success_at DATETIME(3) NULL,
 record_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 parse_errors BIGINT UNSIGNED NOT NULL DEFAULT 0,
 blank_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 source_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 state ENUM('complete','pending','error') NOT NULL DEFAULT 'pending',
 error_code VARCHAR(64) NULL
) ENGINE=InnoDB;
CREATE TABLE access_log_current_records (
 id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 source_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 snapshot_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ordinal BIGINT UNSIGNED NOT NULL,
 occurred_at DATETIME(3) NULL,
 method VARCHAR(20) NULL,
 pathname VARCHAR(2048) NULL,
 status SMALLINT UNSIGNED NULL,
 bytes BIGINT UNSIGNED NULL,
 ip_prefix VARCHAR(64) NULL,
 device_type VARCHAR(30) NULL,
 operating_system VARCHAR(50) NULL,
 browser VARCHAR(50) NULL,
 resource_kind ENUM('page','asset','api','other') NOT NULL,
 is_bot BOOLEAN NOT NULL DEFAULT FALSE,
 referrer VARCHAR(2048) NULL,
 parse_status ENUM('parsed','error') NOT NULL,
 error_code VARCHAR(64) NULL,
 UNIQUE KEY current_position(snapshot_id,ordinal),
 INDEX current_source(source_id,snapshot_id),
 INDEX cache_time(occurred_at,id),
 INDEX current_network(ip_prefix,occurred_at),
 INDEX current_path(pathname(191),occurred_at),
 FOREIGN KEY(source_id) REFERENCES access_log_current_sources(id)
) ENGINE=InnoDB;
